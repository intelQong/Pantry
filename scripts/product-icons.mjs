// Writes src/client/lib/productIconPaths.ts: the SVG bodies of just the
// product icons that src/client/lib/productIcon.ts names, out of the ~1,600
// in the set, so the bundle carries a few dozen rather than all of them.
//
//   node scripts/product-icons.mjs
//
// Re-run after adding or changing a rule. Fails loudly if a rule names an
// icon the set doesn't have, rather than shipping a blank tile.
import { readFileSync, writeFileSync } from "node:fs";

const set = JSON.parse(
  readFileSync("node_modules/@iconify-json/fluent-emoji-high-contrast/icons.json", "utf8"),
);
const rules = readFileSync("src/client/lib/productIcon.ts", "utf8");
const names = [...new Set([...rules.matchAll(/, "([a-z0-9-]+)"\],/g)].map((m) => m[1]))].sort();

const missing = names.filter((n) => !set.icons[n]);
if (missing.length) {
  console.error("Not in the icon set:", missing.join(", "));
  process.exit(1);
}

// Reduced to plain path data, so the app draws icons as ordinary React SVG
// rather than injecting markup. Safe because of what the set contains, which
// is checked here rather than assumed: every shape is a <path> in
// currentColor, and the only clip paths cover the whole 32x32 box (so they
// clip nothing) -- they also all share one id, which would collide once two
// icons sit on the same screen.
const toPaths = (name, body) => {
  const withoutDefs = body.replace(/<defs>.*?<\/defs>/gs, (defs) => {
    if (!/^<defs><clipPath id="[^"]+"><path fill="#fff" d="M0 0h32v32H0z"\/><\/clipPath><\/defs>$/.test(defs)) {
      throw new Error(`${name}: unexpected <defs>, review before reducing it to paths`);
    }
    return "";
  });
  const leftover = withoutDefs.replace(/<\/?g[^>]*>|<path[^>]*\/>/g, "");
  if (leftover.trim()) throw new Error(`${name}: unexpected markup ${leftover.slice(0, 60)}`);
  return [...withoutDefs.matchAll(/<path([^>]*)\/>/g)].map(([, attrs]) => {
    const d = attrs.match(/ d="([^"]+)"/)[1];
    return /fill-rule="evenodd"/.test(attrs) ? { d, evenOdd: true } : { d };
  });
};

const entries = names
  .map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(toPaths(n, set.icons[n].body))},`)
  .join("\n");
writeFileSync(
  "src/client/lib/productIconPaths.ts",
  `// Generated by scripts/product-icons.mjs -- do not edit by hand.
// Fluent Emoji High Contrast, (c) Microsoft Corporation, MIT License:
// https://github.com/microsoft/fluentui-emoji/blob/main/LICENSE
// Each value is the paths of a ${set.width}x${set.height} icon, filled with currentColor.
export const PRODUCT_ICON_PATHS: Record<string, Array<{ d: string; evenOdd?: boolean }>> = {
${entries}
};
`,
);
console.log(`${names.length} icons written`);
